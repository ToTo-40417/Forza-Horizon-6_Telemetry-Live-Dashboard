static const size_t CAR_DATA_COUNT = sizeof(CAR_DATA) / sizeof(CAR_DATA[0]);

const CarDataEntry* findCarData(int32_t ordinal) {
  size_t low = 0;
  size_t high = CAR_DATA_COUNT;
  while (low < high) {
    const size_t mid = low + (high - low) / 2;
    if (CAR_DATA[mid].ordinal < ordinal) {
      low = mid + 1;
    } else {
      high = mid;
    }
  }
  if (low >= CAR_DATA_COUNT || CAR_DATA[low].ordinal != ordinal) return nullptr;
  return &CAR_DATA[low];
}
